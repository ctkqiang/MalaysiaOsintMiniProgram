const dicts: Record<Lang, Dict> = { zh, en, ms }

export function t(lang: Lang, key: string): string {
  return dicts[lang][key] || dicts.zh[key] || key
}

/** 生成页面 data 用的文案对象：只挑当前页面用到的 key */
export function stringsFor(lang: Lang, keys: string[]): Dict {
  const out: Dict = {}
  for (const k of keys) {
    out[k] = t(lang, k)
  }
  return out
}
